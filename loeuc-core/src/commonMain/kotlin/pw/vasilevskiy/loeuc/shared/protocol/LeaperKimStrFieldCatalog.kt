package pw.vasilevskiy.loeuc.shared.protocol

/**
 * How much the description of a field is worth trusting.
 *
 * The distinction is the whole point of this catalogue. Most of these 248 names have never been
 * confirmed against anything, and presenting a plausible guess with the same authority as a measured
 * fact is how a reverse-engineered dashboard starts lying to its user.
 */
enum class LeaperKimStrFieldConfidence {
    /** Verified against a capture, against the firmware, or by the wheel's owner. */
    Confirmed,

    /** The name plus the observed behaviour agree, and nothing contradicts it. Not verified. */
    Likely,

    /** A reading of the name and little else. Treat as a label, not as a meaning. */
    Guess,
}

data class LeaperKimStrField(
    val tag: String,
    val ru: String,
    val en: String,
    /**
     * Unit in Russian, where it is known. Most fields print raw counts whose scale nobody has
     * established, and those carry null.
     */
    val unitRu: String?,
    /** The same unit in English, null exactly where [unitRu] is null. */
    val unitEn: String?,
    val confidence: LeaperKimStrFieldConfidence,
) {
    /** The unit in the requested language, or null when the scale of the field is unknown. */
    fun unit(isRu: Boolean): String? = if (isRu) unitRu else unitEn

    /** The description in the requested language. */
    fun description(isRu: Boolean): String = if (isRu) ru else en
}

